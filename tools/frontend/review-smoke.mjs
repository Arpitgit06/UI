import {chromium} from 'playwright';
import {existsSync,readdirSync} from 'node:fs';
import {mkdir,writeFile} from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';

const base='http://127.0.0.1:8000',job=process.argv[2];
if(!/^[A-Za-z0-9_-]+$/.test(job||''))throw Error('Pass an existing completed two-state job');
const source=await fetch(`${base}/jobs/${job}/review`).then(r=>r.json());
const state=source.states[0],target=source.states.find(s=>s.id!==state.id);
const button=state.nodes.find(n=>n.tag==='button');
if(!button||!target)throw Error('Fixture needs a button and a second state');
const digest=async()=>createHash('sha256').update(Buffer.from(await (await fetch(`${base}/jobs/${job}/download`)).arrayBuffer())).digest('hex');
const before=await digest();
const cache=path.join(process.env.LOCALAPPDATA||'','ms-playwright');
const installed=existsSync(cache)?readdirSync(cache).filter(x=>/^chromium-\d+$/.test(x)).sort().reverse().map(x=>path.join(cache,x,'chrome-win64','chrome.exe')).find(existsSync):undefined;
const browser=await chromium.launch({headless:true,...(installed?{executablePath:installed}:{})});
const report={checks:[],errors:[]};
try{
  const page=await browser.newPage({viewport:{width:1400,height:1100}});
  page.on('pageerror',error=>report.errors.push(error.message));
  await page.goto(`${base}/jobs/${job}/review/ui`);
  await page.getByLabel('Captured state').selectOption(state.id);
  await page.getByLabel('Detected node').selectOption(button.id);
  await page.getByLabel('Text',{exact:true}).fill('Reviewed sign in');
  await page.getByLabel('Font size (px)').fill('18');
  await page.getByRole('button',{name:'Add correction to draft'}).click();
  await page.getByLabel('Destination state').selectOption(target.id);
  await page.getByRole('button',{name:'Confirm selected control’s transition'}).click();
  await page.getByRole('button',{name:'Build and browser-check revision'}).click();
  const output=page.getByRole('link',{name:'Open reviewed UI',exact:true});
  await output.waitFor({timeout:180000});
  const href=await output.getAttribute('href');report.revision=href.split('/')[2];
  report.checks.push('Review UI stages correction, confirms transition and builds a revision');
  const reviewed=await fetch(`${base}/jobs/${report.revision}/review`).then(r=>r.json());
  if(reviewed.actions[state.id]?.[button.id]!==target.id)throw Error('Confirmed action was not exported');
  if(reviewed.states.find(s=>s.id===state.id).nodes.find(n=>n.id===button.id).text!=='Reviewed sign in')throw Error('Text correction missing');
  report.checks.push('Corrected text and confirmed interaction persist in exported design');
  if(await digest()!==before)throw Error('Original archive changed');report.checks.push('Original archive unchanged');
  await page.goto(base+href+'?inspect=1');
  await page.getByRole('combobox',{name:'Captured state'}).selectOption(String(reviewed.states.findIndex(s=>s.id===state.id)));
  await page.getByRole('button',{name:'Reviewed sign in',exact:true}).click();
  await page.waitForFunction(id=>document.querySelector('.omniui-stage')?.dataset.state?.toLowerCase()===id.replaceAll('_','').toLowerCase(),target.id);
  report.checks.push('Reviewed native button reaches confirmed destination in hybrid view');
  await page.locator('.omniui-editable-layer button').first().click();
  await page.getByRole('status').filter({hasText:'No confirmed action'}).waitFor();
  report.checks.push('Unmapped control reports missing behavior instead of silently doing nothing');
  const out=path.resolve('storage/jobs',report.revision,'review-ui-check');await mkdir(out,{recursive:true});
  await page.goto(`${base}/jobs/${job}/review/ui`);
  await page.getByLabel('Detected node').selectOption(button.id);
  await page.screenshot({path:path.join(out,'desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Review UI overflows on mobile');
  await page.screenshot({path:path.join(out,'mobile.png'),fullPage:true});report.checks.push('Review UI fits desktop and mobile');
  if(report.errors.length)throw Error(report.errors.join('; '));report.status='passed';
}catch(error){report.status='failed';report.errors.push(error.message);process.exitCode=1;}
finally{await browser.close();}
await mkdir('storage/jobs/review_evaluation',{recursive:true});
await writeFile('storage/jobs/review_evaluation/result.json',JSON.stringify(report,null,2));
console.log(JSON.stringify(report));
